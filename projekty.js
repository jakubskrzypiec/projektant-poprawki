const projectsGrid = document.querySelector("[data-projects-grid]");

const projectImagePath = (_project, fileName) => fileName;

const createProjectCard = (project, index) => {
  const article = document.createElement("article");
  article.className = "projects-page-card reveal";
  article.dataset.projectCard = "";
  article.dataset.category = project.category;
  article.dataset.title = project.title;
  article.dataset.description = project.description;
  article.dataset.image = projectImagePath(project, project.cover);
  article.dataset.gallery = project.images.map(file => projectImagePath(project, file)).join(",");
  article.dataset.galleryAlts = project.alts.join("|");

  const button = document.createElement("button");
  button.className = "projects-page-card__button";
  button.type = "button";
  button.setAttribute("aria-label", `Otwórz galerię projektu ${project.title}`);

  const head = document.createElement("span");
  head.className = "projects-page-card__head";

  const heading = document.createElement("span");

  const eyebrow = document.createElement("span");
  eyebrow.className = "projects-page-card__eyebrow";
  eyebrow.textContent = project.category;

  const title = document.createElement("span");
  title.className = "projects-page-card__title";
  title.textContent = project.title;

  const number = document.createElement("span");
  number.className = "projects-page-card__number";
  number.setAttribute("aria-hidden", "true");
  number.textContent = String(index + 1).padStart(2, "0");

  heading.append(eyebrow, title);
  head.append(heading, number);

  const media = document.createElement("span");
  media.className = "projects-page-card__media";

  const image = document.createElement("img");
  image.src = projectImagePath(project, project.cover);
  image.alt = `${project.title} - ${project.alts[0] || "widok wnętrza"}`;
  image.loading = index === 0 ? "eager" : "lazy";
  image.decoding = "async";

  const hint = document.createElement("span");
  hint.className = "projects-page-card__hint";
  hint.setAttribute("aria-hidden", "true");
  hint.textContent = "Zobacz galerię →";

  media.append(image, hint);
  button.append(head, media);
  article.append(button);
  return article;
};

if (projectsGrid) {
  const PAGE_SIZE = 6;
  let visibleProjects = Math.min(PAGE_SIZE, projects.length);
  const fragment = document.createDocumentFragment();

  projects.forEach((project, index) => {
    const card = createProjectCard(project, index);
    if (index >= visibleProjects) card.classList.add("is-project-hidden");
    fragment.append(card);
  });

  projectsGrid.append(fragment);

  if (projects.length > PAGE_SIZE) {
    const moreWrap = document.createElement("div");
    moreWrap.className = "projects-page-more-wrap";

    const moreButton = document.createElement("button");
    moreButton.className = "projects-page-more";
    moreButton.type = "button";
    moreButton.textContent = "Pokaż więcej projektów";
    moreButton.setAttribute("aria-controls", "projects-list");

    projectsGrid.id = "projects-list";
    moreWrap.append(moreButton);
    projectsGrid.insertAdjacentElement("afterend", moreWrap);

    moreButton.addEventListener("click", () => {
      const cards = [...projectsGrid.querySelectorAll(".projects-page-card")];
      visibleProjects = Math.min(visibleProjects + PAGE_SIZE, cards.length);

      cards.forEach((card, index) => {
        if (index < visibleProjects) card.classList.remove("is-project-hidden");
      });

      if (visibleProjects >= cards.length) {
        moreButton.hidden = true;
      }
    });
  }
}
